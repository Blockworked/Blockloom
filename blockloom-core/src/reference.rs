//! The components and settings reference (`docs/reference/`), written from
//! the type registry so it can't drift from what the editor draws.

use crate::registry::{self, ComponentType};
use crate::scene::Mode;
use blockloom_plugin_api::schema::{Condition, FieldSchema, FieldType, fill_field_defaults};
use serde_json::Value;
use std::fmt::Write;

/// Nested records deeper than this are listed by type only.
const MAX_DEPTH: usize = 4;
/// Longer defaults are left out of the table.
const MAX_DEFAULT: usize = 48;

/// Every generated page as (file name under `docs/reference/`, markdown).
pub fn pages() -> Vec<(&'static str, String)> {
    vec![
        ("components.md", components()),
        (
            "world.md",
            settings_page(
                "World settings",
                "A scene's look and simulation: `set-property target=world path=...`.",
                &registry::world_fields(),
            ),
        ),
        (
            "settings.md",
            settings_page(
                "Game settings",
                "Settings for the whole game, saved in the project index: `set-property target=settings path=...`.",
                &registry::settings_fields(),
            ),
        ),
    ]
}

fn header(title: &str, intro: &str) -> String {
    format!(
        "# {title}\n\n<!-- Generated by blockloom-core/tests/reference_docs.rs from the type registry. \
         Rerun it with BLESS=1 after a schema change; don't edit by hand. -->\n\n{intro}\n\n"
    )
}

fn components() -> String {
    let mut out = header(
        "Components",
        "Every built-in actor component. Defaults are a 3D world's; a 2D one's lengths are in pixels \
         (see Coordinates and units in CLAUDE.md). Edit one with \
         `set-property target=actor:<id>/<Component> path=... value=...`.",
    );
    let three = registry::component_types(Mode::ThreeD);
    let two = registry::component_types(Mode::TwoD);
    for c in &three {
        let _ = writeln!(out, "- [{}](#{})", c.label, anchor(&c.name));
    }
    out.push('\n');
    for c in &three {
        let flat = two.iter().find(|t| t.name == c.name);
        component(&mut out, c, flat);
    }
    out
}

fn anchor(name: &str) -> String {
    name.to_lowercase()
}

fn component(out: &mut String, c: &ComponentType, flat: Option<&ComponentType>) {
    let _ = writeln!(out, "## {}\n", c.name);
    let mut notes = Vec::new();
    if c.label != c.name {
        notes.push(format!(
            "Add component calls it \"{}\".",
            c.label.trim_end_matches('…')
        ));
    }
    match c.dimension {
        Some("2d") => notes.push("2D worlds only.".into()),
        Some("3d") => notes.push("3D worlds only.".into()),
        _ => {}
    }
    if c.repeatable {
        notes.push("An actor may carry more than one.".into());
    }
    if c.special {
        notes.push("Made by its own command rather than from defaults.".into());
    }
    if flat.is_some_and(|f| f.default != c.default) && c.dimension.is_none() {
        notes.push("A 2D world starts it with its own defaults.".into());
    }
    if !notes.is_empty() {
        let _ = writeln!(out, "{}\n", notes.join(" "));
    }
    // Both dimensions' fields, each marked; the registry drops the other one's.
    let mut fields = registry::component_fields(&c.name);
    fill_field_defaults(&mut fields, &c.default);
    table(out, &fields);
}

fn settings_page(title: &str, intro: &str, fields: &[FieldSchema]) -> String {
    let mut out = header(title, intro);
    for f in fields {
        let _ = writeln!(out, "- [{}](#{})", title_of(f), anchor(&f.name));
    }
    out.push('\n');
    for f in fields {
        let _ = writeln!(out, "## {}\n", f.name);
        if !f.description.is_empty() {
            let _ = writeln!(out, "{}\n", one_line(&f.description));
        }
        let mut rows = Vec::new();
        match &f.ty {
            FieldType::Struct { fields } => walk(&mut rows, &f.name, fields, 1),
            _ => rows.push(row(&f.name, f)),
        }
        print_rows(&mut out, &rows);
    }
    out
}

fn title_of(f: &FieldSchema) -> &str {
    f.ui.as_ref()
        .map(|u| u.label.as_str())
        .filter(|l| !l.is_empty())
        .unwrap_or(&f.name)
}

fn table(out: &mut String, fields: &[FieldSchema]) {
    let mut rows = Vec::new();
    walk(&mut rows, "", fields, 0);
    if rows.is_empty() {
        out.push_str("No fields.\n\n");
    } else {
        print_rows(out, &rows);
    }
}

fn print_rows(out: &mut String, rows: &[[String; 4]]) {
    out.push_str("| Field | Type | Default | About |\n|---|---|---|---|\n");
    for [a, b, c, d] in rows {
        let _ = writeln!(out, "| {a} | {b} | {c} | {d} |");
    }
    out.push('\n');
}

fn join(at: &str, name: &str) -> String {
    if at.is_empty() {
        name.to_string()
    } else {
        format!("{at}.{name}")
    }
}

/// One row per field, nested records spelled as dotted paths.
fn walk(rows: &mut Vec<[String; 4]>, at: &str, fields: &[FieldSchema], depth: usize) {
    for f in fields.iter().filter(|f| f.name != "component") {
        let path = join(at, &f.name);
        rows.push(row(&path, f));
        if depth < MAX_DEPTH {
            nested(rows, &path, &f.ty, depth + 1);
        }
    }
}

fn nested(rows: &mut Vec<[String; 4]>, path: &str, ty: &FieldType, depth: usize) {
    match ty {
        FieldType::Struct { fields } => walk(rows, path, fields, depth),
        FieldType::Optional { inner } => nested(rows, path, inner, depth),
        FieldType::List { item, .. } => nested(rows, &format!("{path}[]"), item, depth),
        FieldType::Map { value } => nested(rows, &format!("{path}.*"), value, depth),
        FieldType::Enum { variants, tag } => {
            for v in variants {
                let at = if tag.is_empty() {
                    format!("{path}.{}", v.name)
                } else {
                    format!("{path} ({})", v.name)
                };
                walk(rows, &at, &v.fields, depth);
                if let Some(inner) = &v.inner {
                    nested(rows, &at, inner, depth);
                }
            }
        }
        _ => {}
    }
}

fn row(path: &str, f: &FieldSchema) -> [String; 4] {
    let mut about = Vec::new();
    if let Some(ui) = &f.ui {
        if !ui.label.is_empty() && ui.label != f.name {
            about.push(format!("**{}**", cell(&ui.label)));
        }
        if let Some(c) = &ui.visible_when {
            about.push(format!("Used when {}.", condition(c)));
        }
        match ui.dimension.as_str() {
            "2d" => about.push("2D only.".into()),
            "3d" => about.push("3D only.".into()),
            _ => {}
        }
        if ui.advanced {
            about.push("Advanced.".into());
        }
    }
    if !f.description.is_empty() {
        about.push(cell(&one_line(&f.description)));
    }
    let unit = f.ui.as_ref().map(|u| u.unit.as_str()).unwrap_or("");
    [
        format!("`{path}`"),
        type_name(&f.ty, unit),
        default(f),
        about.join(" "),
    ]
}

fn type_name(ty: &FieldType, unit: &str) -> String {
    let unit = if unit.is_empty() {
        String::new()
    } else {
        format!(" ({})", cell(unit))
    };
    let range = |min: Option<String>, max: Option<String>| match (min, max) {
        (Some(a), Some(b)) => format!(" {a} to {b}"),
        (Some(a), None) => format!(" from {a}"),
        (None, Some(b)) => format!(" up to {b}"),
        (None, None) => String::new(),
    };
    match ty {
        FieldType::Bool => "switch".into(),
        FieldType::Int { min, max } => format!(
            "whole number{}{unit}",
            range(min.map(|m| m.to_string()), max.map(|m| m.to_string()))
        ),
        FieldType::Number { min, max } => format!(
            "number{}{unit}",
            range(min.map(|m| m.to_string()), max.map(|m| m.to_string()))
        ),
        FieldType::Text { .. } => "text".into(),
        FieldType::Color => "color".into(),
        FieldType::Vec3 => format!("x y z{unit}"),
        FieldType::Choice { options, .. } => format!("one of {}", options_list(options)),
        FieldType::Asset { kind } => format!("{kind} asset"),
        FieldType::Actor => "actor".into(),
        FieldType::List { item, .. } => format!("list of {}", type_name(item, "")),
        FieldType::Struct { .. } => "record".into(),
        FieldType::Map { value } => format!("names to {}", type_name(value, "")),
        FieldType::Optional { inner } => format!("{} or none", type_name(inner, unit.trim())),
        FieldType::Enum { variants, .. } => {
            let names: Vec<String> = variants.iter().map(|v| v.name.clone()).collect();
            format!("one of {}", options_list(&names))
        }
        FieldType::Opaque => "JSON".into(),
    }
}

fn options_list(options: &[String]) -> String {
    let shown: Vec<String> = options
        .iter()
        .take(12)
        .map(|o| format!("`{}`", cell(o)))
        .collect();
    let more = options.len().saturating_sub(12);
    if more > 0 {
        format!("{} and {more} more", shown.join(", "))
    } else {
        shown.join(", ")
    }
}

fn default(f: &FieldSchema) -> String {
    // Ids are minted fresh per default, as `registry::to_json` blanks them.
    let Some(value) = f.default.as_ref().filter(|_| f.name != "id") else {
        return String::new();
    };
    let text = match value {
        Value::Object(map) if map.is_empty() => return String::new(),
        Value::Object(_) => return String::new(),
        Value::String(s) if s.is_empty() => return String::new(),
        Value::String(s) => s.clone(),
        other => other.to_string(),
    };
    if text.chars().count() > MAX_DEFAULT {
        String::new()
    } else {
        format!("`{}`", cell(&text))
    }
}

fn condition(c: &Condition) -> String {
    let mut parts = Vec::new();
    let show = |v: &Value| match v {
        Value::String(s) => s.clone(),
        other => other.to_string(),
    };
    if let Some(v) = &c.equals {
        parts.push(format!("`{}` is `{}`", c.field, show(v)));
    }
    if let Some(v) = &c.not_equals {
        parts.push(format!("`{}` isn't `{}`", c.field, show(v)));
    }
    if !c.one_of.is_empty() {
        let list: Vec<String> = c.one_of.iter().map(show).collect();
        parts.push(format!("`{}` is one of {}", c.field, list.join(", ")));
    }
    if !c.not_one_of.is_empty() {
        let list: Vec<String> = c.not_one_of.iter().map(show).collect();
        parts.push(format!("`{}` is none of {}", c.field, list.join(", ")));
    }
    if parts.is_empty() && !c.field.is_empty() {
        parts.push(format!("`{}` is set", c.field));
    }
    parts.extend(c.all.iter().map(condition));
    parts.join(" and ")
}

/// Doc text on one line, with rustdoc's intra-doc link brackets dropped.
fn one_line(text: &str) -> String {
    text.split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .replace("[`", "`")
        .replace("`]", "`")
}

/// Pipes would split a table cell.
fn cell(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', " ")
}
