//! The editor's QML tests read the type registry from a fixture; this holds
//! it to what Rust says (`BLESS=1` rewrites it), so the cards they test draw
//! Rust's defaults and nothing else.

use blockloom_core::registry;
use blockloom_core::scene::Mode;
use std::path::PathBuf;

#[test]
fn the_qml_registry_fixtures_match_the_registry() {
    let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../blockloom-qt/tests/qml/fixtures");
    for (mode, name) in [(Mode::ThreeD, "Registry3d.js")] {
        let path = dir.join(name);
        let text = format!(
            ".pragma library\n// Generated by blockloom-core/tests/registry_fixture.rs.\nvar registry = {};\n",
            serde_json::to_string(&registry::to_json(mode)).unwrap()
        );
        if std::env::var_os("BLESS").is_some() {
            std::fs::write(&path, &text).unwrap();
            continue;
        }
        let held = std::fs::read_to_string(&path).unwrap_or_default();
        assert!(
            held == text,
            "{name} is stale; rerun with BLESS=1 cargo test -p blockloom-core --test registry_fixture"
        );
    }
}
